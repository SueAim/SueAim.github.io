'use strict';
const assert=require('node:assert/strict');
const W=require('../writing-core.js');
const p={name:'Example Student',email:'private@example.invalid',phone:'555-0100',school:'AIM NJ',story:'I repaired a bicycle with my uncle.',goal:'Complete A&P training.',why:'I enjoy finding mechanical faults.'};
const award={id:'test-award',name:'Example maintenance award',org:'Example Foundation',url:'https://example.invalid/award',amount:'$1,000',benefit:'school',requirements:'Current students',ai:'unknown'};
assert.equal(W.rule({...award,ai:'prohibited'},'allowed'),'prohibited');
assert.equal(W.rule({...award,ai:'limited'},'allowed'),'limited');
assert.equal(W.rule(award,'allowed'),'allowed');
assert.equal(W.rule(award,'anything'),'unknown');
const resume=W.resume(p);
assert(resume.includes('A&P student — certificate not yet earned.'));
assert(resume.includes(p.story));
assert(!resume.includes('Certified A&P'));
const prompt=W.brief(p,award,'Describe your goals','allowed',250);
assert(prompt.includes('Target 250 words'));
assert(prompt.includes(p.story));
assert(!prompt.includes(p.email),'Ordinary writing briefs omit private contact information');
assert(!prompt.includes(p.phone));
assert(W.brief(p,{...award,ai:'prohibited'},'Question','allowed').includes('AI writing is prohibited'));
assert(W.brief(p,award,'','unknown').includes('Do not draft an application essay'));
assert(W.brief(p,award,'Question','allowed',99999).includes('Target 2000 words'));
assert.equal(W.https('javascript:alert(1)'),'');
assert.equal(W.https('http://example.invalid'),'');
assert.equal(W.https('https://example.invalid/award'),award.url);
assert.equal(W.profile({name:'  Name  ',password:'never included'}).name,'Name');
assert(!Object.hasOwn(W.profile({password:'never included'}),'password'));
const packet=W.packet(p,[award],{'test-award':'A specific question'},{},{'test-award':'Preparing'});
assert(packet.includes('Status: Preparing'));
assert(packet.includes('A specific question'));
assert(packet.includes(p.email),'Private download includes contact details intentionally');
const agent=W.agentBrief(p,[{...award,ai:'prohibited'}],{},{});
assert(agent.includes('Do not submit, sign, accept terms'));
assert(agent.includes('Do not bypass site restrictions, CAPTCHAs or login'));
assert(agent.includes('AI writing is prohibited'));
assert(agent.includes('not yet certificated'));
console.log('26 writing, privacy and provider-rule checks passed.');
