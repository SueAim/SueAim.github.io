const assert=require('node:assert/strict');
const L=require('../logic.js');
const c=require('../data/catalog.json');
const day='2026-10-28';
const base={search:'',location:'NJ',status:'all',benefit:'all',amount:'all',gender:'all',community:'all',military:'all',parents:'all',age:'',stage:'all',sort:'recommended'};
const filter=f=>c.records.map(r=>({...r,sourceHealth:undefined,maintenance:undefined})).filter(r=>L.matches(r,{...base,...f},day));
assert.equal(new Set(c.records.map(r=>r.id)).size,c.records.length);
assert(!filter({}).some(r=>r.states.includes('TX')),'NJ view must exclude South-Texas-only attendance');
assert(filter({location:'TX'}).some(r=>r.org==='South Texas PAMA'));
assert(filter({benefit:'cash'}).length>0);
assert(!filter({benefit:'cash'}).some(r=>r.org==='TBX'||r.id==='sonic-impact-tools'),'Tuition awards and tool kits must not appear as student cash');
assert(filter({benefit:'tools'}).every(r=>L.support(r).includes('tools')));
assert(!filter({status:'available'}).some(r=>r.org==='Women in Aviation International'));
assert(!filter({gender:'all-genders'}).some(r=>r.gender==='women'));
assert(filter({gender:'women'}).some(r=>r.org==='NBAA'),'General awards remain visible for women');
assert(filter({community:'Black / African American community'}).some(r=>r.org==='LPA'),'Do not infer ethnicity restrictions from organization names');
assert(!filter({age:'16'}).some(r=>r.org==='LPA'));
assert(filter({age:'42'}).some(r=>r.org==='LPA'));
assert(filter({parents:'specific'}).every(r=>r.parent));
assert(filter({military:'specific'}).some(r=>r.org==='VFW'));
assert(!filter({military:'none'}).some(r=>r.org==='VFW'));
assert.equal(L.status({status:'open',deadline:'2026-10-27',reviewed:day},day),'closed');
assert.equal(L.status({status:'upcoming',opens:'2026-11-02'},'2026-11-03'),'verify','Opening date alone cannot prove applications opened');
assert.equal(L.status({status:'open',reviewed:'2026-01-01'},day),'verify','Old reviews must not imply current availability');
assert(filter({search:'Sonic'}).some(r=>r.value===7102));
assert(filter({amount:'5000:10000'}).every(r=>r.value>=5000&&(r.minValue??r.value)<=10000));
assert(filter({benefit:'job'}).some(r=>r.id==='republic-aim-cadet'));
assert(filter({fit:'aim-nj'}).every(r=>!['other-program','degree-check'].includes(r.fit)));
assert(!filter({fit:'aim-nj'}).some(r=>r.id==='piedmont-tuition-payment'));
assert(filter({career:'conditional-offer',fit:'aim-nj'}).some(r=>r.id==='republic-aim-cadet'));
assert(!filter({career:'conditional-offer'}).some(r=>r.id==='skywest-amt-pathway'));
assert(filter({career:'interview'}).some(r=>r.id==='skywest-amt-pathway'));
assert(filter({provider:'mro'}).every(r=>r.provider==='mro'));
assert(filter({stage:'near-graduation'}).every(r=>r.stage==='near-graduation'));
assert(filter({kind:'awards'}).every(r=>!['program','lead'].includes(r.kind)));
assert(filter({kind:'program'}).every(r=>r.kind==='program'));
assert(!filter({status:'available'}).some(r=>r.id==='air-wisconsin-apprentice'));
assert(!filter({benefit:'cash'}).some(r=>r.benefit==='internship'));
assert(filter({status:'closing'}).every(r=>L.closingSoon(r,day)));
assert(filter({status:'closing'}).some(r=>r.org==='TBX'));
assert(!filter({status:'closing'}).some(r=>r.org==='AEA Educational Foundation'));
assert(filter({status:'upcoming'}).some(r=>r.org==='Choose Aerospace'));
assert(filter({amount:'1000:5000'}).some(r=>r.org==='Soroptimist'),'Published ranges overlap requested value bands');
assert.equal(L.status({status:'upcoming',opensMonth:'2027-06'},'2027-06-05'),'verify');
assert.equal(L.status({status:'upcoming',opensMonth:'2027-06'},'2027-05-31'),'upcoming');
const fixture={status:'open',deadline:'2026-10-28'};
assert(L.visible(fixture,day),'Published deadline date is included');
assert(!L.visible(fixture,'2026-10-29'),'Expired nonrecurring listing is hidden even before the next workflow');
assert(L.visible({...fixture,recurring:true},'2026-10-29'),'Recurring listing remains discoverable');
assert.equal(L.status({...fixture,recurring:true},'2026-10-29'),'closed','Recurring does not mean open');
assert(!L.visible({...fixture,sourceHealth:{state:'missing'}},day),'Missing source is hidden even before deadline');
assert(L.visible({...fixture,sourceHealth:{state:'unconfirmed'}},day),'A transient error is not a permanent deletion');
assert(L.visible({...fixture,opens:'2026-11-02'},'2026-10-29'),'Announced future opening is retained');
assert(!L.visible({...fixture,opens:'2026-10-01'},'2026-10-29'),'Past opening is not evidence of a future recurrence');
assert(filter({benefit:'money',status:'available',fit:'aim-nj'}).some(r=>r.org==='Soroptimist'));
assert(filter({benefit:'money',status:'available',fit:'aim-nj'}).some(r=>r.org==='AEA Educational Foundation'));
assert(filter({benefit:'money',status:'available',fit:'aim-nj'}).some(r=>r.benefit==='exam'));
assert(!filter({benefit:'money'}).some(r=>r.id==='sonic-impact-tools'));
assert(filter({benefit:'money',fit:'all',status:'all'}).some(r=>r.id==='duncan-maintenance-apprentice'));
assert(filter({benefit:'money',fit:'all',status:'all'}).some(r=>r.id==='johnson-nj-amt-intern-2027'));
assert(filter({benefit:'money',status:'available'}).some(r=>r.org==='TechForce Foundation'));
assert(filter({benefit:'money',status:'available'}).some(r=>r.id==='amc-techforce-phoebe-omlie-award'));
console.log('54 meaningful catalog/filter checks passed; '+c.records.length+' records.');
